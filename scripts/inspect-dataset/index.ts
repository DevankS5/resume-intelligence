// WF-01: inspect the supplied dataset before anything is imported (Construction §2.2).
// Reports what actually arrived: file count, checksums, structure, readability, duplicates.
// Usage: npm run inspect:dataset -- "<dataset dir>" [--out docs/IMPORT_MANIFEST.md]
// The generated manifest contains no resume text, only metadata.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, basename } from "node:path";
import { sha256 } from "@domain/hash";
import { parseDocument } from "@parsers/index";
import { contentFingerprint } from "@normalization/text";
import { PipelineError } from "@domain/errors";

const EXPECTED = 47;

async function main() {
  const dir = process.argv[2] ?? "Software Development Assignment Resumes";
  const outIdx = process.argv.indexOf("--out");
  const out = outIdx > 0 ? process.argv[outIdx + 1] : null;

  const entries = (await readdir(dir)).sort();
  const rows: string[] = [];
  const seenSha = new Map<string, string>();
  const seenFp = new Map<string, string>();
  let ok = 0;
  let failed = 0;

  for (const [i, name] of entries.entries()) {
    const bytes = new Uint8Array(await readFile(join(dir, name)));
    const sha = sha256(bytes);
    let status = "READABLE";
    let detail = "";
    let blocks = 0;
    let tableCells = 0;
    let chars = 0;
    let unsupported = "";
    let dup = "";
    if (seenSha.has(sha)) dup = `byte-identical to ${seenSha.get(sha)}`;
    seenSha.set(sha, name);
    try {
      const { parsed } = await parseDocument(bytes, name, `inspect-${i}`);
      blocks = parsed.blocks.length;
      tableCells = parsed.blocks.filter((b) => b.blockType === "TABLE_CELL").length;
      chars = parsed.text.length;
      unsupported = parsed.unsupportedStructures.join("; ");
      const fp = contentFingerprint(parsed.text);
      if (!dup && seenFp.has(fp)) dup = `same text as ${seenFp.get(fp)} (review, not merged)`;
      seenFp.set(fp, name);
      ok++;
    } catch (e) {
      status = e instanceof PipelineError ? e.code : "PARSER_ERROR";
      detail = (e as Error).message.slice(0, 120);
      failed++;
    }
    rows.push(
      `| ${i + 1} | \`${basename(name)}\` | ${bytes.byteLength} | \`${sha.slice(0, 12)}…\` | ${status} | ${blocks} | ${tableCells} | ${chars} | ${unsupported || "—"} | ${dup || detail || "—"} |`,
    );
  }

  const md = [
    "# Import Manifest — initial dataset",
    "",
    `Generated by \`npm run inspect:dataset\` on ${new Date().toISOString().slice(0, 10)}. Metadata only; no resume text.`,
    "",
    "## Actual structure of the supplied dataset",
    "",
    `- Delivered as **${entries.length} individual files** in one folder, not as one composite Word document.`,
    "- Each file is therefore its own source document (`INDIVIDUAL_DOCX`); no segmentation is needed and none is guessed.",
    `- Expected ${EXPECTED}, found ${entries.length}: **${entries.length === EXPECTED ? "reconciled" : "MISMATCH"}**.`,
    `- Readable: ${ok}. Failed: ${failed}.`,
    "",
    "| # | File | Bytes | SHA-256 | Parse status | Blocks | Table cells | Chars | Not extracted | Duplicate / note |",
    "|---|---|---:|---|---|---:|---:|---:|---|---|",
    ...rows,
    "",
  ].join("\n");

  if (out) await writeFile(out, md);
  console.log(md);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
