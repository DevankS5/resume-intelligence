// Generates docs/DATA_QUALITY_REPORT.md from the database (Project overview §10).
// Aggregates only: counts, rates and codes, never resume text. Every metric states its denominator.
// Usage: npm run report:quality
import { writeFile } from "node:fs/promises";
import { adminClient } from "@/lib/supabase/admin";
import type { ExtractionQuality } from "@domain/types";
import type { NormalizedProfile } from "@domain/profile";

const EXPECTED = 47;
const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${((n / d) * 100).toFixed(1)}%`);
const tally = <T extends string>(xs: T[]) => xs.reduce<Record<string, number>>((m, x) => ((m[x] = (m[x] ?? 0) + 1), m), {});
const table = (rows: Record<string, number>) => Object.entries(rows).sort().map(([k, v]) => `| ${k} | ${v} |`).join("\n");

async function main() {
  const db = adminClient();
  const { data: resumes } = await db.from("resume_documents").select("id, processing_status, last_error_code, source_documents(source_metadata)");
  const { data: profiles } = await db.from("candidate_profiles").select("resume_id, normalized_profile, extraction_quality, classification").eq("is_current", true);
  const { data: assessments } = await db.from("candidate_assessments").select("score_band, review_flags, jobs(job_key), candidate_profiles!inner(is_current)").eq("candidate_profiles.is_current", true);
  const { data: reviews } = await db.from("review_events").select("id");

  const initial = (resumes ?? []).filter((r) => (r.source_documents as unknown as { source_metadata: { batch?: string } }).source_metadata?.batch === "initial-47");
  const ps = (profiles ?? []).map((p) => ({ p: p.normalized_profile as NormalizedProfile, q: p.extraction_quality as ExtractionQuality, c: p.classification as string }));
  const ev = ps.reduce((a, x) => ({ t: a.t + x.p.evidenceStats.total, v: a.v + x.p.evidenceStats.verified }), { t: 0, v: 0 });
  const roles = ps.flatMap((x) => x.p.experience.filter((e) => e.relevance !== "UNRELATED" || e.experienceType === "PROFESSIONAL"));
  const dateIssues = roles.filter((e) => e.dateStatus !== "COMPLETE").length;
  const injections = ps.filter((x) => x.p.suspiciousContent.length > 0).length;
  const bands = (k: string) => tally((assessments ?? []).filter((a) => (a.jobs as unknown as { job_key: string }).job_key === k).map((a) => a.score_band as string));

  const md = `# Data Quality Report

Generated by \`npm run report:quality\` on ${new Date().toISOString().slice(0, 10)} from the live database. Aggregates only.

## Record accounting

| Metric | Value | Denominator |
|---|---:|---|
| Expected initial records | ${EXPECTED} | assignment brief |
| Initial records received | ${initial.length} | files in the dataset folder |
| Uploaded since | ${(resumes ?? []).length - initial.length} | live uploads |
| Scored (completed or completed with review) | ${(resumes ?? []).filter((r) => ["COMPLETED", "REVIEW_REQUIRED"].includes(r.processing_status)).length} | all records |
| Failed | ${(resumes ?? []).filter((r) => r.processing_status === "FAILED").length} | all records |
| Unaccounted | ${Math.max(0, EXPECTED - initial.length)} | expected minus received |

### Processing status

| Status | Count |
|---|---:|
${table(tally((resumes ?? []).map((r) => r.processing_status as string)))}

### Error codes

| Code | Count |
|---|---:|
${table(tally((resumes ?? []).filter((r) => r.last_error_code).map((r) => r.last_error_code as string))) || "| none | 0 |"}

## Extraction quality (${ps.length} current profiles)

| Metric | Value | Denominator |
|---|---:|---|
| Schema-valid extractions | ${ps.length} | profiles (invalid output never becomes a profile) |
| Evidence quotes verified in source | ${pct(ev.v, ev.t)} (${ev.v}/${ev.t}) | all quotes returned by the model |
| Relevant roles with month-precise dates | ${pct(roles.length - dateIssues, roles.length)} (${roles.length - dateIssues}/${roles.length}) | relevant or professional roles |
| Profiles with text addressed to an automated reader | ${injections} | profiles |
| Manual review events recorded | ${(reviews ?? []).length} | all review events |

| Quality status | Count |
|---|---:|
${table(tally(ps.map((x) => x.q.status)))}

## Assessment outcome

| Routing label | Count |
|---|---:|
${table(tally(ps.map((x) => x.c)))}

| LCA band | Count |
|---|---:|
${table(bands("LCA_CONSULTANT"))}

| UI/UX band | Count |
|---|---:|
${table(bands("UIUX_INTERN"))}

A verified quote proves the passage exists in the resume, not that the interpretation is right; there is no single "accuracy" figure. See KNOWN_LIMITATIONS.md.
`;
  await writeFile("docs/DATA_QUALITY_REPORT.md", md);
  console.log(md);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
