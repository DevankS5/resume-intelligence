// Generates the rubric seed migration from packages/domain/rubrics.ts so the database
// and the scoring engine can never disagree about weights. A unit test fails if the
// committed migration drifts from this output.
// Usage: npx tsx scripts/reports/rubric-seed.ts > supabase/migrations/<ts>_seed_rubrics_v1.sql
import { RUBRICS, validateRubric } from "@domain/rubrics";
import { DESCRIPTIONS } from "./jd-text";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function rubricSeedSql(): string {
  const out = ["-- GENERATED by scripts/reports/rubric-seed.ts from packages/domain/rubrics.ts. Do not edit by hand.", ""];
  for (const r of Object.values(RUBRICS)) {
    const errors = validateRubric(r);
    if (errors.length) throw new Error(`${r.jobKey}: ${errors.join("; ")}`);
    out.push(
      `insert into public.jobs (job_key, title, jd_version, description, location_label, work_mode) values (${q(r.jobKey)}, ${q(r.title)}, ${q(r.jdVersion)}, ${q(DESCRIPTIONS[r.jobKey])}, ${q(r.location)}, ${q(r.workMode)}) on conflict (job_key, jd_version) do nothing;`,
    );
    for (const c of r.criteria) {
      out.push(
        `insert into public.job_criteria (job_id, rubric_version, criterion_key, label, description, weight, mandatory_verification, evidence_guidance, display_order) select id, ${q(r.rubricVersion)}, ${q(c.key)}, ${q(c.label)}, ${q(c.description)}, ${c.weight}, ${c.mandatoryVerification}, ${q(JSON.stringify(c.evidenceGuidance))}::jsonb, ${c.order} from public.jobs where job_key = ${q(r.jobKey)} and jd_version = ${q(r.jdVersion)} on conflict (job_id, rubric_version, criterion_key) do nothing;`,
      );
    }
    out.push("");
  }
  return out.join("\n");
}

if (process.argv[1]?.endsWith("rubric-seed.ts")) process.stdout.write(rubricSeedSql());
